package space.astro.api.central.controllers.guild_settings

import com.aventrix.jnanoid.jnanoid.NanoIdUtils
import io.swagger.v3.oas.annotations.Operation
import io.swagger.v3.oas.annotations.tags.Tag
import org.springframework.http.ResponseEntity
import org.springframework.web.bind.annotation.DeleteMapping
import org.springframework.web.bind.annotation.PathVariable
import org.springframework.web.bind.annotation.PostMapping
import org.springframework.web.bind.annotation.RequestBody
import org.springframework.web.bind.annotation.RestController
import space.astro.api.central.components.middlewares.CanManageGuildMiddleware
import space.astro.shared.core.clients.PremiumManager
import space.astro.shared.core.exceptions.ANotFoundException
import space.astro.shared.core.exceptions.APremiumRequiredException
import space.astro.shared.core.models.database.guildSettings.GuildSettingsEntity
import space.astro.shared.core.models.database.guildSettings.TemplateData
import space.astro.shared.core.repositories.mongo.GuildSettingsRepository
import space.astro.shared.core.utils.api.CentralApiEndpoint

@RestController
@Tag(name = "Templates settings")
class GuildTemplatesController(
    private val guildSettingsRepository: GuildSettingsRepository,
    private val premiumManager: PremiumManager,
) {
    @Operation(summary = "Create template")
    @PostMapping(CentralApiEndpoint.GUILD_SETTINGS_TEMPLATES)
    @CanManageGuildMiddleware
    fun createTemplate(
        @PathVariable guildId: String,
        @RequestBody templateCreateBody: TemplateData,
    ): ResponseEntity<GuildSettingsEntity> {
        val guildSettings =
            guildSettingsRepository.findByGuildID(guildId)
                ?: throw ANotFoundException("Guild with ID $guildId not found in Astro database")

        if (!premiumManager.canCreateTemplate(guildSettings)) {
            throw APremiumRequiredException("Upgrade the server to create more than ${PremiumManager.FREE_MAX_TEMPLATES} templates")
        }

        // the id is always generated by us, whatever the client sent
        guildSettings.templates.add(templateCreateBody.copy(id = NanoIdUtils.randomNanoId()))
        guildSettingsRepository.save(guildSettings)
        return ResponseEntity.ok(guildSettings)
    }

    @Operation(summary = "Update template")
    @PostMapping(CentralApiEndpoint.GUILD_SETTINGS_TEMPLATE)
    @CanManageGuildMiddleware
    fun updateTemplate(
        @PathVariable guildId: String,
        @PathVariable templateId: String,
        @RequestBody updatedTemplateData: TemplateData,
    ): ResponseEntity<GuildSettingsEntity> {
        val guildSettings =
            guildSettingsRepository.findByGuildID(guildId)
                ?: throw ANotFoundException("Guild with ID $guildId not found in Astro database")

        val templateIndex =
            guildSettings.templates
                .indexOfFirst { it.id == templateId }
                .takeIf { it != -1 }
                ?: throw ANotFoundException("Template with ID $templateId not found for guild with id $guildId")

        guildSettings.templates[templateIndex] = updatedTemplateData.copy(id = templateId)
        guildSettingsRepository.save(guildSettings)
        return ResponseEntity.ok(guildSettings)
    }

    @Operation(summary = "Delete template")
    @DeleteMapping(CentralApiEndpoint.GUILD_SETTINGS_TEMPLATE)
    @CanManageGuildMiddleware
    fun deleteTemplate(
        @PathVariable guildId: String,
        @PathVariable templateId: String,
    ): ResponseEntity<GuildSettingsEntity> {
        val guildSettings =
            guildSettingsRepository.findByGuildID(guildId)
                ?: throw ANotFoundException("Guild with ID $guildId not found in Astro database")

        guildSettings.templates.removeIf { it.id == templateId }
        guildSettingsRepository.save(guildSettings)
        return ResponseEntity.ok(guildSettings)
    }
}
